#!/usr/bin/env node
'use strict';

// Build one offline-capable browser asset from the reviewed, date-keyed catalogs.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const lyrics = JSON.parse(fs.readFileSync(path.join(root, 'data/classic-rock-lyrics.json'), 'utf8'));
const history = JSON.parse(fs.readFileSync(path.join(root, 'data/history-calendar.json'), 'utf8'));
if (!Array.isArray(lyrics) || lyrics.length < 366) throw new Error('At least 366 different songs are required.');
if (Object.keys(history).length !== 366) throw new Error('History must cover all 366 calendar dates.');
const normalize = value => value.normalize('NFKD').toLowerCase().replace(/[^a-z0-9]/g, '');
const songs = new Set(), clues = new Set();
lyrics.forEach(entry => {
  if (![entry.lyric, entry.song, entry.artist].every(value => typeof value === 'string' && value.trim())) {
    throw new Error('Every lyric needs a clue, song and artist.');
  }
  if (entry.lyric.trim().split(/\s+/).length > 10) throw new Error('Lyric excerpts must stay at 10 words or fewer.');
  const song = normalize(entry.song), clue = normalize(entry.lyric);
  if (songs.has(song) || clues.has(clue)) throw new Error('Duplicate song or clue: ' + entry.song);
  songs.add(song); clues.add(clue);
});
for (let day = new Date('2000-01-01T12:00:00Z'); day.getUTCFullYear() === 2000; day.setUTCDate(day.getUTCDate() + 1)) {
  const key = day.toISOString().slice(5, 10), entries = history[key];
  if (!Array.isArray(entries) || !entries.length) throw new Error('Missing history: ' + key);
  entries.forEach(entry => {
    if (entry.sourceDate !== key || !Number.isInteger(entry.year) || !entry.text || !/^https:\/\//.test(entry.source)) {
      throw new Error('Undated or invalid history record: ' + key);
    }
  });
}

const output = `/* Generated by tools/build-fun-zone.cjs. Edit the source catalogs, then rebuild.
 * History sources and attribution: data/history-sources.md.
 * Daily selections use America/New_York on every device, without a network request.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.BasementFunDaily = factory();
}(typeof window !== 'undefined' ? window : this, function () {
  'use strict';
  const lyrics = ${JSON.stringify(lyrics)};
  const history = ${JSON.stringify(history)};
  const timeZone = 'America/New_York';
  const formatter = new Intl.DateTimeFormat('en-US', {
    timeZone: timeZone, year: 'numeric', month: '2-digit', day: '2-digit'
  });
  const months = ['January','February','March','April','May','June','July','August','September','October','November','December'];
  const DAY = 86400000;
  function modulo(value, length) { return ((value % length) + length) % length; }
  function pad(value) { return String(value).padStart(2, '0'); }
  function dateParts(date) {
    const parts = formatter.formatToParts(date === undefined ? new Date() : date);
    const values = {};
    parts.forEach(function (part) { if (part.type !== 'literal') values[part.type] = Number(part.value); });
    const year = values.year, month = values.month, day = values.day;
    const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / DAY);
    const monthDay = pad(month) + '-' + pad(day);
    return {
      year: year, month: month, day: day, monthDay: monthDay,
      dateKey: year + '-' + monthDay,
      dateLabel: months[month - 1] + ' ' + day,
      dayNumber: dayNumber,
      dayOfYear: dayNumber - Math.floor(Date.UTC(year, 0, 1) / DAY) + 1
    };
  }

  // Shuffle a complete deck once using a fixed seed. Advancing one slot per
  // Eastern calendar day guarantees no repeat until every song has appeared.
  // Never reset on January 1: the guarantee also holds across year boundaries.
  const rotation = lyrics.map(function (_, index) { return index; });
  let seed = 0x43485249;
  for (let i = rotation.length - 1; i > 0; i--) {
    seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5;
    const j = (seed >>> 0) % (i + 1);
    const item = rotation[i]; rotation[i] = rotation[j]; rotation[j] = item;
  }
  function calendar(date) {
    const result = dateParts(date);
    result.lyric = lyrics[rotation[modulo(result.dayNumber, rotation.length)]] || null;
    const events = (history[result.monthDay] || []).filter(function (event) {
      return event.sourceDate === result.monthDay && Number.isInteger(event.year) && event.year <= result.year;
    });
    // Missing data stays missing. Never substitute an event from another date.
    result.history = events.length ? events[modulo(result.year, events.length)] : null;
    return result;
  }
  return { timeZone: timeZone, lyrics: lyrics, history: history, rotation: rotation, dateParts: dateParts, calendar: calendar };
}));
`;

const target = path.join(root, 'fun-zone-daily.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    throw new Error('fun-zone-daily.js is out of date. Run node tools/build-fun-zone.cjs.');
  }
  console.log('Fun Zone bundle matches the source catalogs.');
} else {
  fs.writeFileSync(target, output);
  console.log('Built Fun Zone bundle: ' + lyrics.length + ' songs, ' + Object.keys(history).length + ' calendar dates.');
}
